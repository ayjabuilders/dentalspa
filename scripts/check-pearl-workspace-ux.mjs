/* global document, window */
import {readFileSync} from 'node:fs';
import {chromium,expect} from '@playwright/test';
const check=expect.configure({timeout:30000});
const browser=await chromium.launch();
try {
 const credentials=JSON.parse(readFileSync('.local/owner-demo-access.json','utf8'));
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://localhost:4204/connection?view=patients');
 await page.getByLabel('Adresse e-mail',{exact:true}).fill(credentials.email);
 await page.getByLabel('Mot de passe',{exact:true}).fill(credentials.password);
 await page.getByRole('button',{name:'Se connecter',exact:true}).click();
 const rail=page.getByRole('navigation',{name:'Modules du cabinet'});
 await check(rail).toBeVisible();
 await check.poll(async()=>(await rail.boundingBox()).width).toBeLessThan(100);
 await page.getByRole('button',{name:'Développer le menu',exact:true}).click();
 await check.poll(async()=>(await rail.boundingBox()).width).toBeGreaterThan(180);
 await page.getByRole('button',{name:'Réduire le menu',exact:true}).click();
 await page.keyboard.press('Control+k');
 let dialog=page.getByRole('dialog');
 await check(dialog.getByLabel('Rechercher un module')).toBeFocused();
 await dialog.getByLabel('Rechercher un module').fill('agenda');
 await check(dialog.getByRole('button',{name:/Calendrier et rendez-vous/})).toBeVisible();
 await dialog.getByRole('button',{name:/Calendrier et rendez-vous/}).click();
 await check(page.getByRole('heading',{name:'Agenda des patients',exact:true})).toBeVisible();
 await page.getByRole('navigation',{name:'Parcours entre modules'}).getByRole('button',{name:'Précédent',exact:true}).click();
 await check(page.getByRole('heading',{name:'Vos patients',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Compte et cabinet',exact:true}).click();
 dialog=page.getByRole('dialog');await check(dialog.getByRole('button',{name:'Changer de cabinet',exact:true})).toBeVisible();
 await check(dialog.getByRole('button',{name:'Se déconnecter',exact:true})).toBeVisible();
 await page.keyboard.press('Escape');await check(page.getByRole('button',{name:'Compte et cabinet',exact:true})).toBeFocused();
 await page.getByRole('button',{name:'Liste',exact:true}).click();
 const patientRow=page.locator('.directory-record').first();
 await check(patientRow).toBeVisible();
 const comfortableHeight=(await patientRow.boundingBox()).height;
 await page.getByRole('button',{name:'Préférences de présentation',exact:true}).click();
 dialog=page.getByRole('dialog');await dialog.getByRole('switch',{name:'Affichage compact',exact:true}).click();
 await check(page.locator('main')).toHaveAttribute('data-density','compact');
 await dialog.getByRole('switch',{name:'Animations',exact:true}).click();
 await check(page.locator('main')).toHaveAttribute('data-motion','reduced');
 await page.keyboard.press('Escape');
 await check.poll(async()=>(await patientRow.boundingBox()).height).toBeLessThan(comfortableHeight);
 await check.poll(async()=>(await patientRow.boundingBox()).height).toBeGreaterThanOrEqual(44);
 await page.screenshot({path:'.local/qa/pearl-ux-shell.png'});
 await rail.getByRole('button',{name:'Agenda',exact:true}).click();
 await check(page.locator('.recorded-appointments').first()).toHaveAttribute('aria-busy','false');await page.screenshot({path:'.local/qa/pearl-ux-agenda.png'});
 await rail.getByRole('button',{name:'Messagerie',exact:true}).click();
 await check(page.locator('.fake-inbox')).toHaveAttribute('aria-busy','false');await page.screenshot({path:'.local/qa/pearl-ux-inbox.png'});
 await page.setViewportSize({width:390,height:844});
 await check.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await rail.getByRole('button',{name:'Patients',exact:true}).click();
 await page.screenshot({path:'.local/qa/pearl-ux-shell-mobile.png'});
 if(errors.length)throw Error(errors.join('\n'));
 console.log('PASS compact/expanded rail, keyboard module search, contextual history, account actions/focus, density/motion preferences and mobile navigation.');
}finally{await browser.close();}
