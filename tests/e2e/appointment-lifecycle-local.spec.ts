import { test,expect } from '@playwright/test';
test('native agenda moves then cancels a persisted appointment',async({page},info)=>{
  test.setTimeout(90000);
  const {LOCAL_PATIENT_HUB_EMAIL:email,LOCAL_PATIENT_HUB_PASSWORD:password,LOCAL_APPOINTMENT_ID:id,LOCAL_APPOINTMENT_DATE:date}=process.env;
  test.skip(!email||!password||!id||!date,'Use the local lifecycle runner for isolated fixtures.');
  await page.goto('http://localhost:4204/connection?view=planning');
  await page.getByLabel('Adresse e-mail',{exact:true}).fill(email!);await page.getByLabel('Mot de passe',{exact:true}).fill(password!);
  await page.getByRole('button',{name:'Se connecter',exact:true}).click();
  await page.getByLabel('À partir du',{exact:true}).fill(date!);
  const row=page.locator(`[data-appointment-id="${id}"]`);
  await expect(row.locator('time')).toHaveText('14:00');
  await row.getByRole('button',{name:'Déplacer',exact:true}).click();
  await row.getByLabel('Nouvelle date',{exact:true}).fill(date!);
  await row.getByLabel('Heure de Casablanca',{exact:true}).fill('16:00');
  await row.getByRole('button',{name:'Enregistrer le déplacement',exact:true}).click();
  await expect(row.locator('time')).toHaveText('16:00');
  await page.getByRole('button',{name:'Actualiser',exact:true}).click();
  await expect(row.locator('time')).toHaveText('16:00');
  await row.getByRole('button',{name:'Annuler',exact:true}).click();
  await row.getByRole('button',{name:'Confirmer l’annulation',exact:true}).click();
  await expect(row.getByText('Annulé',{exact:true})).toBeVisible();
  await expect(row.getByRole('button',{name:'Déplacer',exact:true})).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.locator('.recorded-appointments').screenshot({path:info.outputPath('appointment-cancelled-mobile.png')});
  await row.getByRole('button',{name:'Ouvrir le dossier de Salma Alaoui (FICTIF)',exact:true}).click();
  const hub=page.getByRole('region',{name:'Dossier patient enregistré'});
  await hub.getByRole('tab',{name:'Rendez-vous',exact:true}).click();
  await expect(hub.getByText('Annulé · 45 min',{exact:true})).toBeVisible();
});
