import { expect, test, type Page } from '@playwright/test';
const base = process.env.PATIENT_PASS_URL ?? 'http://localhost:4205';
const nav = (page: Page, name: string) => page.getByRole('navigation', { name: 'Navigation Patient Pass' }).getByRole('button', { name, exact: true });
async function scenario(page: Page, name: string) { await page.getByRole('button', { name: 'Changer d’exemple' }).click(); await page.getByRole('dialog', { name: 'Explorer un profil fictif' }).getByRole('button', { name: new RegExp(name) }).click(); }

test('message drafts survive tabs in memory and reset when the scenario or document changes', async ({ page }) => {
  const apiRequests: string[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname.includes('/api/')) apiRequests.push(request.url()); });
  await page.goto(base);
  await scenario(page, 'Yasmine Benjelloun');
  await nav(page, 'Messages').click();
  await page.getByLabel('Votre brouillon fictif', { exact: true }).fill('Exemple administratif français.');
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await page.getByLabel('مسودة تجريبية', { exact: true }).fill('مثال إداري تجريبي');
  await page.getByRole('button', { name: 'Aperçu uniquement', exact: true }).click();
  await page.getByRole('button', { name: 'Marquer l’exemple comme lu', exact: true }).click();
  await nav(page, 'Accueil').click();
  await expect(page.locator('.messages-demo')).toBeHidden();
  await expect(page.getByRole('textbox')).toHaveCount(0);
  await expect(page.getByRole('status').filter({ hasText: 'معاينة المسودة' })).toHaveCount(0);
  await nav(page, 'Messages').click();
  await expect(page.getByLabel('مسودة تجريبية', { exact: true })).toHaveValue('مثال إداري تجريبي');
  await expect(page.getByRole('article', { name: 'Conversation fictive en arabe' })).toHaveAttribute('dir', 'rtl');
  await expect(page.getByRole('status')).toContainText('معاينة المسودة');
  await expect(page.getByText('Lu dans cet aperçu', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Français', exact: true }).click();
  await expect(page.getByLabel('Votre brouillon fictif', { exact: true })).toHaveValue('Exemple administratif français.');
  await nav(page, 'Dossier').click(); await nav(page, 'Messages').click();
  await expect(page.getByLabel('Votre brouillon fictif', { exact: true })).toHaveValue('Exemple administratif français.');
  await scenario(page, 'Imane El Idrissi'); await nav(page, 'Messages').click();
  await expect(page.getByLabel('Votre brouillon fictif', { exact: true })).toHaveValue('');
  await scenario(page, 'Yasmine Benjelloun'); await nav(page, 'Messages').click();
  await expect(page.getByLabel('Votre brouillon fictif', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.getByLabel('مسودة تجريبية', { exact: true })).toHaveValue('');
  await page.getByLabel('مسودة تجريبية', { exact: true }).fill('مثال جديد');
  await page.reload(); await nav(page, 'Messages').click();
  await expect(page.getByLabel('Votre brouillon fictif', { exact: true })).toHaveValue('');
  await page.getByRole('button', { name: 'العربية', exact: true }).click();
  await expect(page.getByLabel('مسودة تجريبية', { exact: true })).toHaveValue('');
  expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
  expect(apiRequests).toEqual([]);
});

test('entering and leaving a verified session removes demo message drafts', async ({ page }) => {
  const cors = { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': '*', 'Access-Control-Allow-Methods': 'GET,POST,OPTIONS', 'Cache-Control': 'no-store' };
  const user = '10000000-0000-4000-8000-000000000001', clinic = '10000000-0000-4000-8000-000000000002', patient = '10000000-0000-4000-8000-000000000003';
  await page.route('**/auth/v1/token**', route => route.fulfill(route.request().method() === 'OPTIONS' ? { status: 204, headers: cors } : { headers: cors, json: { access_token: 'synthetic-access-token', token_type: 'bearer', refresh_token: 'synthetic-refresh-token', expires_in: 3600, expires_at: Math.floor(Date.now() / 1000) + 3600, user: { id: user, aud: 'authenticated', role: 'authenticated', email: 'patient@example.invalid', app_metadata: { provider: 'email' }, user_metadata: {}, created_at: '2026-10-26T10:00:00Z' } } }));
  await page.route('**/rest/v1/patient_account_links**', route => route.fulfill(route.request().method() === 'OPTIONS' ? { status: 204, headers: cors } : { headers: { ...cors, 'Content-Range': '0-0/1' }, json: [{ user_id: user, clinic_id: clinic, patient_id: patient, verified_at: '2026-10-26T12:00:00Z' }] }));
  await page.route('**/api/v1/me/patient', route => route.fulfill(route.request().method() === 'OPTIONS' ? { status: 204, headers: cors } : { headers: cors, json: { id: patient, clinic_id: clinic, display_name: 'Profil patient fictif', reference: 'DS-QA-001' } }));
  await page.route('**/api/v1/me/preferences', route => route.fulfill({ status: 503, headers: cors, json: {} }));
  await page.route('**/auth/v1/logout**', route => route.fulfill({ status: 204, headers: cors }));
  await page.goto(base);
  await nav(page, 'Messages').click();
  await page.getByLabel('Votre brouillon fictif', { exact: true }).fill('Exemple avant connexion.');
  await nav(page, 'Compte').click();
  test.skip(await page.getByLabel('Adresse e-mail', { exact: true }).count() === 0, 'This build intentionally has no configured patient sign-in.');
  await page.getByLabel('Adresse e-mail', { exact: true }).fill('patient@example.invalid');
  await page.getByRole('textbox', { name: 'Mot de passe', exact: true }).fill('synthetic-password');
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click();
  await expect(page.getByText('Session vérifiée · contenu limité à votre compte')).toBeVisible();
  await nav(page, 'Messages').click();
  await expect(page.locator('.messages-demo')).toHaveCount(0);
  await nav(page, 'Compte').click();
  await page.getByRole('button', { name: 'Se déconnecter', exact: true }).click();
  await nav(page, 'Messages').click();
  await expect(page.getByLabel('Votre brouillon fictif', { exact: true })).toHaveValue('');
  expect(await page.evaluate(() => localStorage.length + sessionStorage.length)).toBe(0);
});
