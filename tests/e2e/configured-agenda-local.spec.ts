import {test,expect} from '@playwright/test';
test('persisted manager settings feed real local public availability',async({page},info)=>{
  test.setTimeout(90000);
  const {LOCAL_PATIENT_HUB_EMAIL:email,LOCAL_PATIENT_HUB_PASSWORD:password,LOCAL_AGENDA_DATE:date}=process.env;
  test.skip(!email||!password||!date,'Run the native configured agenda runner.');
  await page.goto('http://localhost:4204/connection?view=agenda-settings');
  await page.getByLabel('Adresse e-mail',{exact:true}).fill(email!);await page.getByLabel('Mot de passe',{exact:true}).fill(password!);
  await page.getByRole('button',{name:'Se connecter',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Paramètres de l’agenda',exact:true})).toBeVisible();
  await page.getByRole('tab',{name:/^Visites/}).click();
  await expect(page.getByLabel('Nom du type',{exact:true}).first()).toHaveValue('Première visite — fictive');
  await page.getByRole('button',{name:'Enregistrer les paramètres',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:/Version \d+ enregistrée/})).toBeVisible();
  await page.getByRole('button',{name:'Retour à l’agenda',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Agenda des patients',exact:true})).toBeVisible();
  await expect(page.getByLabel('Mot de passe',{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:'Paramètres',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Paramètres de l’agenda',exact:true})).toBeVisible();
  await expect(page.getByLabel('Mot de passe',{exact:true})).toHaveCount(0);
  await page.goto('http://localhost:4202/#availability');
  const availability=page.locator('#availability');
  await availability.getByLabel('Date de visite',{exact:true}).fill(date!);
  await expect(availability.getByRole('option',{name:'Première visite — fictive · 30 min',exact:true})).toHaveCount(1);
  await expect(availability.getByRole('option',{name:/Contrôle/})).toHaveCount(0);
  await availability.getByRole('combobox',{name:'Type de visite',exact:true}).selectOption('81000000-0000-4000-8000-000000000001');
  await expect(availability.getByText('09:00 – 09:30',{exact:true})).toBeVisible();
  await expect(availability.getByRole('alert')).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await availability.screenshot({path:info.outputPath('configured-agenda-native-mobile.png')});
});
