import {test,expect} from '@playwright/test';
test('native manager catalogue persists edits archive restore and recovers a lost response',async({page})=>{
  test.setTimeout(90000);
  const email=process.env.LOCAL_CATALOG_EMAIL,password=process.env.LOCAL_CATALOG_PASSWORD,code=process.env.LOCAL_CATALOG_CODE;
  test.skip(!email||!password||!code,'Use the local catalogue runner.');
  await page.goto('http://localhost:4204/connection?view=finance-catalog');

  const signIn=async()=>{await page.getByLabel('Adresse e-mail',{exact:true}).fill(email!);await page.getByLabel('Mot de passe',{exact:true}).fill(password!);await page.getByRole('button',{name:'Se connecter',exact:true}).click();};
  await signIn();
  const catalog=page.getByRole('region',{name:'Catalogue tarifaire',exact:true});
  await expect(catalog).toBeVisible();
  const commands:Array<{key:string|undefined;body:unknown}>=[];
  await page.route('**/api/v1/finance/services',async route=>{
    if(route.request().method()!=='POST')return route.continue();
    commands.push({key:route.request().headers()['idempotency-key'],body:route.request().postDataJSON()});
    const response=await route.fetch();expect(response.status()).toBe(201);
    if(commands.length===1)await route.abort('failed');else await route.fulfill({response});
  });
  await catalog.getByRole('button',{name:'Ajouter une prestation',exact:true}).click();
  const form=page.getByRole('form',{name:'Édition de prestation',exact:true});
  await expect(page.getByRole('dialog',{name:'Nouvelle prestation',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(catalog.getByRole('button',{name:'Ajouter une prestation',exact:true})).toBeFocused();
  await catalog.getByRole('button',{name:'Ajouter une prestation',exact:true}).click();
  await expect(form.getByLabel('Code',{exact:true})).toHaveCount(0);
  await form.getByLabel('Libellé',{exact:true}).fill(code!);
  await page.keyboard.press('Escape');await expect(form.getByText('Abandonner les modifications non enregistrées ?')).toBeVisible();
  await form.getByRole('button',{name:'Continuer la saisie',exact:true}).click();

  await form.getByLabel('Catégorie',{exact:true}).selectOption('Consultation');
  await form.getByLabel('Prix en MAD',{exact:true}).fill('125,50');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await form.screenshot({path:'.local/qa/finance-catalog-form-mobile.png'});
  await form.getByRole('button',{name:'Enregistrer la prestation',exact:true}).click();
  await expect(form.getByRole('alert')).toContainText('Résultat à vérifier');
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toBeVisible();
  await expect(form.getByRole('button',{name:'Fermer',exact:true})).toBeDisabled();
  await form.getByRole('button',{name:'Réessayer la même commande',exact:true}).click();
  await expect(form).toHaveCount(0);expect(commands).toHaveLength(2);expect(commands[0]!.key).toBeTruthy();expect(commands[0]).toEqual(commands[1]);
  await catalog.getByRole('textbox',{name:'Rechercher une prestation',exact:true}).fill(code!);
  const row=catalog.locator('.catalog-list > li');
  await expect(row).toHaveCount(1);await expect(row).toContainText('125,50');await expect(row).toContainText('Consultation');
  await row.getByRole('button',{name:'Modifier '+code!,exact:true}).click();
  await form.getByLabel('Prix en MAD',{exact:true}).fill('150.00');
  await form.getByRole('button',{name:'Enregistrer la prestation',exact:true}).click();
  await expect(row).toContainText('version 2');await expect(row).toContainText('150,00');
  await row.getByRole('button',{name:'Modifier '+code!,exact:true}).click();
  await form.getByRole('checkbox',{name:'Archiver la prestation',exact:true}).check();
  await form.getByRole('button',{name:'Enregistrer la prestation',exact:true}).click();
  await expect(form).toHaveCount(0);await expect(row).toHaveCount(0);
  await catalog.getByRole('checkbox',{name:'Afficher les prestations archivées',exact:true}).check();
  await expect(row).toContainText('Archivée · version 3');
  await row.getByRole('button',{name:'Modifier '+code!,exact:true}).click();
  await form.getByRole('checkbox',{name:'Archiver la prestation',exact:true}).uncheck();
  await form.getByRole('button',{name:'Enregistrer la prestation',exact:true}).click();
  await expect(row).toContainText('Active · version 4');
  await page.reload();
  await catalog.getByRole('textbox',{name:'Rechercher une prestation',exact:true}).fill(code!);
  await expect(row).toContainText('Active · version 4');await expect(row).toContainText('150,00');
  await catalog.screenshot({path:'.local/qa/finance-catalog-mobile.png'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await catalog.getByRole('button',{name:'Dossiers & devis',exact:true}).click();
  await expect(page.getByRole('button',{name:'Ouvrir la fiche de Salma Alaoui (FICTIF)',exact:true})).toBeVisible();
  await expect(page.getByLabel('Mot de passe',{exact:true})).toHaveCount(0);
  await page.getByRole('navigation',{name:'Modules du cabinet'}).getByRole('button',{name:'Catalogue tarifaire',exact:true}).click();
  await expect(catalog).toBeVisible();
});
