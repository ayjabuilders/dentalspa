import { expect, test } from '@playwright/test';

const clinicUrl = process.env.CLINIC_DEMO_UI_URL ?? 'http://localhost:4204';

test('single selected workflow editor preserves order, dependencies, validation and local-only state', async ({ page }) => {
  const apiRequests: string[] = [];
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiRequests.push(request.url()); });
  await page.goto(`${clinicUrl}/playbook`);
  await expect(page.getByRole('heading', { name: 'Modèles de tâches' })).toBeVisible();
  await expect(page.getByText('Le brouillon reste dans cette page et s’efface au rechargement.', { exact: false })).toBeVisible();
  await page.getByLabel('Nom du modèle').fill('Organisation administrative');
  const add = page.getByRole('button', { name: 'Ajouter une tâche' });
  await add.focus(); await page.keyboard.press('Enter');
  const taskTitle = page.getByLabel('Titre de tâche');
  await expect(taskTitle).toBeFocused();
  await taskTitle.fill('Préparer le dossier administratif');
  await page.getByLabel('Accueil', { exact: true }).check();
  await add.click();
  await expect(taskTitle).toBeFocused();
  await taskTitle.fill('Relire les éléments fournis');
  await page.getByLabel('Gestionnaire', { exact: true }).check();
  await page.getByLabel('Préparer le dossier administratif', { exact: true }).check();
  await expect(page.locator('.workflow-draft-task')).toHaveCount(1);
  await expect(page.locator('.workflow-draft-task-select')).toHaveCount(2);
  await page.getByRole('button', { name: 'Valider ce brouillon' }).click();
  await expect(page.getByRole('status')).toContainText('Brouillon valide sur cette page');

  const outline = page.locator('.workflow-draft-task-select');
  await outline.nth(0).click();
  await expect(taskTitle).toBeFocused();
  await expect(taskTitle).toHaveValue('Préparer le dossier administratif');
  await page.getByLabel('Relire les éléments fournis', { exact: true }).check();
  await page.getByRole('button', { name: 'Valider ce brouillon' }).click();
  await expect(page.locator('.workflow-draft-errors')).toContainText('Ces dépendances créent une boucle');
  await page.getByLabel('Relire les éléments fournis', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Descendre Préparer le dossier administratif', exact: true }).click();
  await expect(outline.nth(0)).toContainText('Relire les éléments fournis');
  await expect(outline.nth(1)).toBeFocused();
  await expect(taskTitle).toHaveValue('Préparer le dossier administratif');
  await page.getByRole('button', { name: 'Supprimer Préparer le dossier administratif', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(outline).toHaveCount(1);
  await expect(outline.first()).toBeFocused();
  await expect(taskTitle).toHaveValue('Relire les éléments fournis');
  await page.getByRole('button', { name: 'Valider ce brouillon' }).click();
  await expect(page.getByRole('status')).toContainText('Brouillon valide sur cette page');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Commencez par une tâche' })).toBeVisible();
  expect(apiRequests).toEqual([]);
});

test('clearing a nonempty local draft requires confirmation and restores useful focus', async ({ page }) => {
  await page.goto(`${clinicUrl}/playbook`);
  const clear = page.getByRole('button', { name: 'Effacer', exact: true });
  await expect(clear).toBeDisabled();
  await page.getByLabel('Nom du modèle').fill('Organisation administrative');
  await page.getByRole('button', { name: 'Ajouter une tâche' }).click();
  await page.getByLabel('Titre de tâche').fill('Préparer les documents');
  await clear.click();
  const dialog = page.getByRole('dialog', { name: 'Effacer le brouillon ?' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Conserver le brouillon' })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(clear).toBeFocused();
  await expect(page.getByLabel('Titre de tâche')).toHaveValue('Préparer les documents');
  await clear.click();
  await dialog.getByRole('button', { name: 'Conserver le brouillon' }).click();
  await expect(page.getByLabel('Nom du modèle')).toHaveValue('Organisation administrative');
  await clear.click();
  await dialog.getByRole('button', { name: 'Effacer le brouillon', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByLabel('Nom du modèle')).toBeFocused();
  await expect(page.getByLabel('Nom du modèle')).toHaveValue('');
  await expect(page.getByRole('heading', { name: 'Commencez par une tâche' })).toBeVisible();
  await page.getByRole('button', { name: 'Ajouter une tâche' }).click();
  await page.getByRole('button', { name: 'Supprimer la tâche 1', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Ajouter une tâche' })).toBeFocused();
});
