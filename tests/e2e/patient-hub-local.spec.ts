import { test, expect } from '@playwright/test';
const email=process.env.LOCAL_PATIENT_HUB_EMAIL,password=process.env.LOCAL_PATIENT_HUB_PASSWORD;
test('native patient dossier survives reload with linked appointments documents and quotes',async({page},testInfo)=>{
  test.setTimeout(60000);
  test.skip(!email||!password,'Use scripts/run-local-patient-hub-e2e.mjs for temporary local Auth.');
  async function open(){
    await page.goto('http://localhost:4204/connection?view=patients');
    await page.getByLabel('Adresse e-mail',{exact:true}).fill(email!);
    await page.getByLabel('Mot de passe',{exact:true}).fill(password!);
    await page.getByRole('button',{name:'Se connecter',exact:true}).click();
    await page.getByRole('button',{name:'Ouvrir la fiche de Salma Alaoui (FICTIF)',exact:true}).click();
    await expect(page.getByRole('region',{name:'Dossier patient enregistré'}).getByText('salma@example.test',{exact:true})).toBeVisible();
  }
  await open();
  const hub=page.getByRole('region',{name:'Dossier patient enregistré'});
  await hub.getByRole('tab',{name:'Rendez-vous',exact:true}).click();
  const appointment=hub.getByRole('list',{name:'Rendez-vous du patient'}).getByRole('listitem').first();
  await expect(appointment.getByText('Confirmé',{exact:true})).toBeVisible();
  await expect(appointment.getByText('45 min',{exact:true})).toBeVisible();
  await hub.getByRole('tab',{name:'Documents',exact:true}).click();
  await expect(hub.getByText('À fournir',{exact:true})).toBeVisible();
  await hub.getByRole('tab',{name:'Devis',exact:true}).click();
  await expect(hub.locator('.patient-quotes > .patient-quote').first().locator(':scope > summary')).toContainText('Devis 1');
  await expect(hub.locator('.patient-quotes > .patient-quote').first().locator('.financial-quote-amount')).toContainText('300');
  await hub.locator('.patient-quote summary').click();
  await expect(hub.locator('.patient-quote').first().getByText('Consultation initiale fictive', {exact:true})).toBeVisible();
  await expect(hub.getByText('Total du brouillon', {exact:true})).toBeVisible();
  await expect(hub.getByText('Version enregistrée · non émise · non publiée au patient', {exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await hub.screenshot({path:'.local/qa/patient-quote-mobile.png'});
  await page.setViewportSize({width:1280,height:900});
  if(process.env.LOCAL_QUOTE_CREATION_KEY){
    const commands:Array<{key:string|undefined;body:unknown}>=[];
    await page.route('**/api/v1/finance/patients/*/quotes',async route=>{
      const headers={...route.request().headers(),'idempotency-key':process.env.LOCAL_QUOTE_CREATION_KEY!};
      commands.push({key:route.request().headers()['idempotency-key'],body:route.request().postDataJSON()});
      const response=await route.fetch({headers});expect(response.status()).toBe(201);
      if(commands.length===1)await route.abort('failed');else await route.fulfill({response});
    });
    await hub.getByRole('button',{name:'Nouveau devis brouillon',exact:true}).click();
    const form=page.getByRole('dialog',{name:'Nouveau devis brouillon',exact:true});
    await form.getByRole('checkbox',{name:/Consultation initiale fictive/}).check();
    await form.getByRole('spinbutton',{name:'Quantité',exact:true}).fill('2');
    await form.getByRole('button',{name:'Enregistrer le brouillon',exact:true}).click();
    await expect(form.getByRole('alert')).toContainText('Résultat à vérifier');
    await expect(form.getByRole('button',{name:'Fermer',exact:true})).toBeDisabled();
    await form.getByRole('button',{name:'Réessayer la même création',exact:true}).click();
    await expect(hub.getByText(/Devis 2 · 600/)).toBeVisible();
    expect(commands).toHaveLength(2);expect(commands[0]!.key).toBeTruthy();expect(commands[0]).toEqual(commands[1]);
    await hub.screenshot({path:'.local/qa/patient-created-quote-desktop.png'});
    const revisions:Array<{key:string|undefined;body:unknown}>=[];
    await page.route('**/api/v1/finance/patients/*/quotes/*/revisions',async route=>{
      revisions.push({key:route.request().headers()['idempotency-key'],body:route.request().postDataJSON()});
      const response=await route.fetch({headers:{...route.request().headers(),'idempotency-key':process.env.LOCAL_QUOTE_REVISION_KEY!}});expect(response.status()).toBe(201);
      if(revisions.length===1)await route.abort('failed');else await route.fulfill({response});
    });
    await hub.getByText(/Devis 2 · 600/).click();
    const revisedQuote=hub.locator('.patient-quotes > .patient-quote').nth(1);
    await revisedQuote.getByRole('button',{name:'Modifier ce brouillon',exact:true}).click();
    const edit=page.getByRole('dialog',{name:'Modifier le devis brouillon',exact:true});
    await expect(edit.getByRole('spinbutton',{name:'Quantité',exact:true})).toHaveValue('2');
    await edit.getByRole('spinbutton',{name:'Quantité',exact:true}).fill('3');
    await page.setViewportSize({width:390,height:844});
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
    await edit.screenshot({path:'.local/qa/quote-revision-form-mobile.png'});
    await edit.getByRole('button',{name:'Enregistrer la nouvelle version',exact:true}).click();
    await expect(edit.getByRole('alert')).toContainText('Résultat à vérifier');
    await edit.getByRole('button',{name:'Réessayer la même création',exact:true}).click();
    await expect(hub.getByText(/Devis 2 · 900/)).toBeVisible();
    expect(revisions).toHaveLength(2);expect(revisions[0]!.key).toBeTruthy();expect(revisions[0]).toEqual(revisions[1]);
    await hub.getByText(/Devis 2 · 900/).click();
    await revisedQuote.getByText('Historique des versions (1)',{exact:true}).click();
    await revisedQuote.getByText(/Version 1 · 600/).click();
    await expect(revisedQuote.getByText('Version précédente conservée',{exact:true})).toBeVisible();
    await revisedQuote.screenshot({path:'.local/qa/quote-history-mobile.png'});
    await page.setViewportSize({width:1280,height:900});
  }
  await hub.getByRole('tab',{name:'Synthèse',exact:true}).click();
  await hub.screenshot({path:testInfo.outputPath('patient-hub-desktop.png')});
  await page.reload();await open();
  await hub.getByRole('tab',{name:'Devis',exact:true}).click();
  await hub.locator('.patient-quote summary').first().click();
  if(process.env.LOCAL_QUOTE_CREATION_KEY)await expect(hub.getByText(/Devis 2 · 900/)).toBeVisible();
  await expect(hub.locator('.patient-quote').first().getByText('Consultation initiale fictive', {exact:true})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await hub.screenshot({path:testInfo.outputPath('patient-hub-mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.goto('http://localhost:4204/connection?view=planning');
  await page.getByLabel('Adresse e-mail',{exact:true}).fill(email!);
  await page.getByLabel('Mot de passe',{exact:true}).fill(password!);
  await page.getByRole('button',{name:'Se connecter',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Agenda des patients',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Ouvrir le dossier de Salma Alaoui (FICTIF)',exact:true})).toBeVisible();
  await page.locator('.recorded-appointments').screenshot({path:testInfo.outputPath('recorded-agenda-mobile.png')});
  await page.setViewportSize({width:1280,height:900});
  await expect.poll(()=>page.locator('.recorded-appointments').evaluate(element=>element.getBoundingClientRect().width)).toBeGreaterThan(900);
  await page.locator('.recorded-appointments').screenshot({path:testInfo.outputPath('recorded-agenda-desktop.png')});
  await page.getByRole('button',{name:'Ouvrir le dossier de Salma Alaoui (FICTIF)',exact:true}).click();
  await expect(hub.getByText('salma@example.test',{exact:true})).toBeVisible();
  await expect(page.getByLabel('Mot de passe',{exact:true})).toHaveCount(0);
});
